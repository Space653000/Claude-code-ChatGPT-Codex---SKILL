#!/usr/bin/env node

import {
  existsSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const buckets = ["engineering", "productivity", "in-progress", "misc"];
const titles = {
  engineering: "Engineering",
  productivity: "Productivity",
  "in-progress": "In progress",
  misc: "Specialized",
};
const catalogPath = join(
  repo,
  "skills",
  "engineering",
  "ask-matt",
  "CATALOG.md",
);

function scalar(frontmatter, key, { indented = false } = {}) {
  const prefix = indented ? "  " : "";
  const match = frontmatter.match(
    new RegExp(`^${prefix}${key}:\\s*(.+)$`, "m"),
  );
  if (!match) return undefined;
  const value = match[1].trim();
  if (value.startsWith('"') && value.endsWith('"')) {
    try {
      return JSON.parse(value);
    } catch {
      return value.slice(1, -1);
    }
  }
  if (value.startsWith("'") && value.endsWith("'")) {
    return value.slice(1, -1).replaceAll("''", "'");
  }
  return value;
}

function skillEntries() {
  return buckets.flatMap((bucket) => {
    const root = join(repo, "skills", bucket);
    return readdirSync(root, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => {
        const path = join(root, entry.name, "SKILL.md");
        if (!existsSync(path)) return undefined;
        const content = readFileSync(path, "utf8");
        const frontmatter = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
        if (!frontmatter) {
          throw new Error(`${path}: missing YAML frontmatter`);
        }
        const name = scalar(frontmatter[1], "name");
        const description = scalar(frontmatter[1], "description");
        if (!name || !description) {
          throw new Error(`${path}: missing name or description`);
        }
        return {
          bucket,
          name,
          description,
          origin: scalar(frontmatter[1], "origin", { indented: true }),
        };
      })
      .filter(Boolean);
  });
}

function originLabel(origin) {
  if (origin === "public-derived") return "Public-derived original";
  if (origin === "repository-original") return "Repository original";
  return "Matt Pocock snapshot";
}

function statusLabel(bucket) {
  if (bucket === "in-progress") return "Beta";
  if (bucket === "misc") return "Specialized";
  return "Stable";
}

function escapeCell(value) {
  return value.replaceAll("|", "\\|").replaceAll(/\r?\n/g, " ");
}

function renderCatalog(entries) {
  const lines = [
    "# Complete skill catalog",
    "",
    `Generated from ${entries.length} canonical \`SKILL.md\` files. Do not edit this file by hand.`,
    "",
    "Read this catalog when the host skill listing is shortened, the best route",
    "is unclear, or the request may match a beta or specialized skill. Choose the",
    "smallest relevant set, then call the Skill tool by name.",
  ];

  for (const bucket of buckets) {
    const rows = entries
      .filter((entry) => entry.bucket === bucket)
      .sort((a, b) => {
        if (a.name === "ask-matt") return -1;
        if (b.name === "ask-matt") return 1;
        return a.name.localeCompare(b.name);
      });
    lines.push(
      "",
      `## ${titles[bucket]}`,
      "",
      "| Skill | Status | Origin | Automatic trigger |",
      "| --- | --- | --- | --- |",
    );
    for (const entry of rows) {
      lines.push(
        `| \`${entry.name}\` | ${statusLabel(bucket)} | ${originLabel(entry.origin)} | ${escapeCell(entry.description)} |`,
      );
    }
  }

  return `${lines.join("\n")}\n`;
}

const rendered = renderCatalog(skillEntries());
if (process.argv.includes("--check")) {
  if (!existsSync(catalogPath) || readFileSync(catalogPath, "utf8") !== rendered) {
    throw new Error(
      "Skill catalog is out of date. Run npm run sync-skill-catalog.",
    );
  }
  console.log("Complete skill catalog is up to date");
  process.exit(0);
}

writeFileSync(catalogPath, rendered, "utf8");
console.log("Complete skill catalog synchronized");
